/** locales with authored management strings; everything else shows English (and stays LTR) */
const MGMT_LOCALES: Partial<Record<Locale, Record<MgmtKey, string>>> = { en: MGMT_EN, he: MGMT_HE };

export type Mgmt = {
  locale: Locale;
  dir: "rtl" | "ltr";
  t: (key: MgmtKey, vars?: Record<string, string | number>) => string;
  /** "1 branch" / "{n} branches" */
  branches: (n: number) => string;
  region: (id: RegionId) => string;
};

/** pure — usable on the server (await getLocale()) and in client components (useMgmt) */
export function mgmt(locale: Locale): Mgmt {
  const dict = MGMT_LOCALES[locale] ?? MGMT_EN;
  const t = (key: MgmtKey, vars?: Record<string, string | number>) => {
    let s = dict[key] ?? MGMT_EN[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
    return s;
  };
  return {
    locale,
    dir: locale === "he" ? "rtl" : "ltr",
    t,
    branches: (n) => (n === 1 ? t("common.branchOne") : t("common.branchMany", { n })),
    region: (id) => t(`region.${id}` as MgmtKey),
  };
}
