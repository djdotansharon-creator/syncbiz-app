const PHRASES: Record<string, Record<string, string> | undefined> = { he: HE_PHRASES };

/** Hebrew (or any language that has a phrasebook) for an English UI sentence; the English text itself when there is no entry. */
export function trFor(locale: string, text: string, vars?: Record<string, string | number>): string {
  let out = PHRASES[locale]?.[text] ?? text;
  if (vars) for (const [k, v] of Object.entries(vars)) out = out.split(`{${k}}`).join(String(v));
  return out;
}
